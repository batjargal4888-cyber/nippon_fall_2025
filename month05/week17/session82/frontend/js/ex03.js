// Бөглөх

let grade = 75;

// 1. Үнэлгээ тооцох
if (grade >= 90) {
    console.log("A");
} else if (grade >= 80) {
    console.log("B");
} else if (grade >= 70) {
    console.log("C");
} else if (grade >= 60) {
    console.log("D");
} else {
    console.log("F");
}

// 2. Цаг агаар
let temp = 15;
if (temp > 30) {
    console.log("Халуун");
} else if (temp > 20) {
    console.log("Дулаахан");
} else if (temp > 10) {
    console.log("Сэрүүхэн");
} else {
    console.log("Хүйтэн");
}

// 3. Насны ангилал
let userAge = 25;
if (userAge < 13) {
    console.log("Хүүхэд");
} else if (userAge < 18) {
    console.log("Өсвөр нас");
} else if (userAge < 25) {
    console.log("Залуу");
} else {
    console.log("Насанд хүрэгч");
}
